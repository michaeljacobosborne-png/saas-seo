/**
 * Saving an audit as a shareable report for outreach, without the public
 * unlock flow. Used by `scripts/save-audit.ts --share`.
 *
 * The public analyzer saves a report only through /api/audit/lead, which emails
 * whoever's address is entered. Outreach needs a link to paste into a message
 * to a stranger, and must never email them, so this writes the row directly:
 *   - a fixed internal address (the column is NOT NULL) that nothing sends to
 *   - source "outreach", no user, so it never appears in anyone's dashboard
 *   - no promoted score columns, so it never enters a benchmark
 * The share token is generated by the database (gen_random_uuid default).
 */
export const OUTREACH_EMAIL = 'outreach@bylineseo.com'
export const OUTREACH_SOURCE = 'outreach'
export const REPORT_SITE = 'https://app.bylineseo.com'

export function outreachRow(report: { url: string; finalUrl?: string }, tool: 'geo' | 'ao') {
  const target = report.finalUrl || report.url
  return {
    email: OUTREACH_EMAIL,
    source: OUTREACH_SOURCE,
    tool,
    url: target,
    domain: new URL(target).hostname.replace(/^www\./, ''),
    result: report,
    user_id: null,
    retrievability_score: null,
    citability_band: null,
  }
}

export function reportLinks(row: { id: string; share_token: string }) {
  return {
    reportUrl: `${REPORT_SITE}/report/${row.share_token}`,
    resultsUrl: `${REPORT_SITE}/audit/results/${row.id}`,
  }
}
